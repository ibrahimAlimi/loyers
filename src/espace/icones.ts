const sansAccents = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

export function chercherIcones(recherche: string): string[] {
  const q = sansAccents(recherche.trim());
  const noms = Object.keys(BIBLIOTHEQUE_ICONES);
  if (!q) return noms;
  return noms.filter((n) => sansAccents(`${n} ${BIBLIOTHEQUE_ICONES[n].mots}`).includes(q));
}

/** Icône choisie par l'espace pour une entrée du menu, sinon l'icône par défaut. */
export function iconeMenu(cle: string, parDefaut: Icon, choix: Record<string, string> | null | undefined): Icon {
  const nom = choix?.[cle];
  return (nom && BIBLIOTHEQUE_ICONES[nom]?.icone) || parDefaut;
}
